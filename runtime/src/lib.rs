/// Natively, what the crate hands out stays `Send` (and `Sync` where it was): [`MaybeSend`] relaxes bounds on
/// WebAssembly only.
#[cfg(all(test, not(target_family = "wasm")))]
mod send_tests {
    use super::*;

    fn send_sync<T: Send + Sync>() {}
    fn send<T: Send>(_: &T) {}

    #[test]
    fn natively_clients_bodies_and_futures_are_send() {
        send_sync::<Client>();
        send_sync::<HttpService>();
        send_sync::<Body>();
        send_sync::<Response>();
        send_sync::<RequestBuilder>();
        send_sync::<Upload>();
        send_sync::<multipart::Form>();
        send_sync::<ProviderLayer>();
        let request = Client::default().request(Method::GET, "https://example.com/");
        send(&request.send());
        let response = Response::from(http::Response::new(Body::empty()));
        let events = Response::from(http::Response::new(Body::empty())).events();
        send(&events);
        send(&events.json::<serde_json::Value>());
        send(&response.bytes_stream());
        #[cfg(feature = "time")]
        send(
            &sse::Events::from_bytes(futures_util::stream::empty::<Result<&'static [u8], Error>>())
                .idle_timeout(std::time::Duration::from_secs(1)),
        );
    }
}
